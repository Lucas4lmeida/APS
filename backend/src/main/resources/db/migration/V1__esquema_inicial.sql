-- Esquema inicial do MVP (fatia do aluno), seguindo docs/arquitetura.md, seção 3.2.
-- As demais tabelas (equivalencia, periodo_matricula, oferta, bloco_horario,
-- horario_indisponivel, planejamento, planejamento_disciplina) entram em migrações
-- futuras, junto com as funcionalidades que as usam.

-- Usuários: generalização total e exclusiva (ALUNO, COORDENADOR, ADMIN_INSTITUCIONAL)
CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    nome       VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    papel      VARCHAR(30)  NOT NULL,
    -- O back-end grava o e-mail em minúsculas
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('ALUNO', 'COORDENADOR', 'ADMIN_INSTITUCIONAL'))
);

CREATE TABLE curso (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20)  NOT NULL,
    nome   VARCHAR(255) NOT NULL,
    CONSTRAINT uk_curso_codigo UNIQUE (codigo)
);

CREATE TABLE fluxo (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id                    BIGINT      NOT NULL REFERENCES curso (id),
    nome                        VARCHAR(20) NOT NULL,
    vigencia_inicio             VARCHAR(6)  NOT NULL,
    status                      VARCHAR(20) NOT NULL,
    creditos_optativos_exigidos INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uk_fluxo_curso_nome UNIQUE (curso_id, nome),
    CONSTRAINT ck_fluxo_status CHECK (status IN ('RASCUNHO', 'PUBLICADO')),
    CONSTRAINT ck_fluxo_vigencia CHECK (vigencia_inicio ~ '^[0-9]{4}\.[12]$'),
    CONSTRAINT ck_fluxo_creditos_optativos CHECK (creditos_optativos_exigidos >= 0)
);

CREATE TABLE aluno (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    matricula  VARCHAR(20) NOT NULL,
    fluxo_id   BIGINT REFERENCES fluxo (id),
    CONSTRAINT uk_aluno_matricula UNIQUE (matricula)
);

CREATE TABLE coordenador (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    curso_id   BIGINT NOT NULL REFERENCES curso (id)
);

CREATE TABLE admin_institucional (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE
);

-- Entidade fraca (fluxo, numero)
CREATE TABLE semestre_fluxo (
    fluxo_id BIGINT  NOT NULL REFERENCES fluxo (id) ON DELETE CASCADE,
    numero   INTEGER NOT NULL,
    titulo   VARCHAR(100),
    PRIMARY KEY (fluxo_id, numero),
    CONSTRAINT ck_semestre_numero CHECK (numero BETWEEN 1 AND 98)
);

CREATE TABLE disciplina (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fluxo_id      BIGINT       NOT NULL REFERENCES fluxo (id) ON DELETE CASCADE,
    codigo        VARCHAR(20)  NOT NULL,
    nome          VARCHAR(255) NOT NULL,
    creditos      INTEGER      NOT NULL DEFAULT 0,
    carga_horaria INTEGER      NOT NULL DEFAULT 0,
    tipo          VARCHAR(20)  NOT NULL,
    semestre      INTEGER,
    ordem         INTEGER      NOT NULL DEFAULT 0,
    pendente      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_disciplina_fluxo_codigo UNIQUE (fluxo_id, codigo),
    CONSTRAINT fk_disciplina_semestre FOREIGN KEY (fluxo_id, semestre) REFERENCES semestre_fluxo (fluxo_id, numero),
    CONSTRAINT ck_disciplina_tipo CHECK (tipo IN ('OBRIGATORIA', 'OPTATIVA', 'EXTERNA')),
    -- Só a obrigatória tem semestre; optativas ficam no catálogo e externas fora das linhas
    CONSTRAINT ck_disciplina_semestre CHECK ((tipo = 'OBRIGATORIA') = (semestre IS NOT NULL)),
    -- "pendente" só faz sentido para pré-requisito externo vindo de código não encontrado no CSV
    CONSTRAINT ck_disciplina_pendente CHECK (NOT pendente OR tipo = 'EXTERNA'),
    CONSTRAINT ck_disciplina_creditos CHECK (creditos >= 0 AND carga_horaria >= 0)
);

CREATE INDEX ix_disciplina_fluxo ON disciplina (fluxo_id);

-- Auto-relacionamento N:N "exige" (relação "E": todos precisam estar cumpridos)
CREATE TABLE pre_requisito (
    disciplina_id BIGINT NOT NULL REFERENCES disciplina (id) ON DELETE CASCADE,
    requisito_id  BIGINT NOT NULL REFERENCES disciplina (id) ON DELETE CASCADE,
    PRIMARY KEY (disciplina_id, requisito_id),
    CONSTRAINT ck_pre_requisito_proprio CHECK (disciplina_id <> requisito_id)
);

CREATE INDEX ix_pre_requisito_requisito ON pre_requisito (requisito_id);

-- Registro das disciplinas do aluno: só Cursada e Cursando são guardados.
-- Disponível e Bloqueada são calculados (docs/arquitetura.md, seção 5).
CREATE TABLE cursa (
    aluno_id      BIGINT      NOT NULL REFERENCES aluno (usuario_id) ON DELETE CASCADE,
    disciplina_id BIGINT      NOT NULL REFERENCES disciplina (id),
    situacao      VARCHAR(20) NOT NULL,
    PRIMARY KEY (aluno_id, disciplina_id),
    CONSTRAINT ck_cursa_situacao CHECK (situacao IN ('CURSANDO', 'CURSADA'))
);

CREATE INDEX ix_cursa_disciplina ON cursa (disciplina_id);
